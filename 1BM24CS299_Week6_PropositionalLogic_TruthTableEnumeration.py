from itertools import product

def implies(a, b):
    return not a or b

# Check all possible truth assignments
models = []

print(f"{'P':^7}{'Q':^7}{'R':^7}| {'Q->P':^7}{'P->~Q':^7}{'Q|R':^7}| {'KB':^7}")
print("-" * 62)

for P, Q, R in product([False, True], repeat=3):

    a = implies(Q, P)
    b = implies(P, not Q)
    c = Q or R

    KB = a and b and c

    models.append((P, Q, R, KB))

    print(f"{str(P):^7}{str(Q):^7}{str(R):^7}| {str(a):^7}{str(b):^7}{str(c):^7}| {str(KB):^7}")


# Check whether KB entails a query
def entails(query):
    for P, Q, R, KB in models:

        if KB and not query(P, Q, R):
            return False

    return True


# Three queries
q1 = lambda P, Q, R: R
q2 = lambda P, Q, R: implies(R, P)
q3 = lambda P, Q, R: implies(Q, R)

print("\nQuery R:", entails(q1))
print("Query R -> P:", entails(q2))
print("Query Q -> R:", entails(q3))