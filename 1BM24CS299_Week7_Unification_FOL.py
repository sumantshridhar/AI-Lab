def is_variable(word):
    return word.islower()


def simple_unify(expr1, expr2):

    if len(expr1) != len(expr2):
        return None

    substitutions = {}

    for i in range(len(expr1)):
        item1 = expr1[i]
        item2 = expr2[i]

        if item1 in substitutions:
            item1 = substitutions[item1]
        if item2 in substitutions:
            item2 = substitutions[item2]

        if item1 == item2:
            continue

        elif is_variable(item1):
            substitutions[item1] = item2

        elif is_variable(item2):
            substitutions[item2] = item1

        else:
            return None  # Unification failed

    return substitutions

statement1 = ["Eats", "x", "Apple"]
statement2 = ["Eats", "Riya", "y"]
print("Statement 1:", statement1)
print("Statement 2:", statement2)


result = simple_unify(statement1, statement2)

if result is None:
    print("Unification Failed!")
else:
    print("Unification Successful!")
    print("Substitutions:", result)