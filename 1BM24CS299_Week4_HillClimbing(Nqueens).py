# Hill Climbing for 4-Queens

def cost(state):
    conflicts = 0

    for i in range(4):
        for j in range(i + 1, 4):

            if state[i] == state[j]:
                conflicts += 1

            elif abs(state[i] - state[j]) == abs(i - j):
                conflicts += 1

    return conflicts


def hill_climbing():
    current = [3, 1, 2, 0]

    while True:
        print("Current state:", current)
        print("Current cost:", cost(current))

        best = current[:]

        # Try swapping every pair of queens
        for i in range(4):
            for j in range(i + 1, 4):
                neighbor = current[:]

                neighbor[i], neighbor[j] = neighbor[j], neighbor[i]

                print("Neighbor:", neighbor,
                      "Cost:", cost(neighbor))

                if cost(neighbor) < cost(best):
                    best = neighbor

        # Stop if no better neighbor exists
        if cost(best) >= cost(current):
            break

        current = best
        print()

    print("\nFinal state:", current)
    print("Final cost:", cost(current))

    if cost(current) == 0:
        print("Solution found!")


hill_climbing()

