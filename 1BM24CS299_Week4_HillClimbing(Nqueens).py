# Function to print the 4x4 chessboard





def print_grid(state):
    n = len(state)

    print("+" + "---+" * n)

    for row in range(n):
        print("|", end="")

        for col in range(n):
            if state[row] == col:
                print(" Q |", end="")
            else:
                print("   |", end="")

        print()
        print("+" + "---+" * n)




