# Function to print the 8x8 chessboard with grid lines
def print_grid(board):
    print("+---" * 8 + "+")

    for row in range(8):
        print("|", end="")

        for col in range(8):
            if board[col] == row:
                print(" Q |", end="")
            else:
                print("   |", end="")

        print()
        print("+---" * 8 + "+")


