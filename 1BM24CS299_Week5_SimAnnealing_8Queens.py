import random
import math

def cost(board):
    count = 0
    for i in range(8):
        for j in range(i + 1, 8):
          if board[i] == board[j]:
                count += 1

          if abs(board[i] - board[j]) == abs(i - j):
                count += 1


    return count

def simulated_annealing():
    board = [random.randint(0, 7) for i in range(8)]
    T = 1000 #INITIAL HIGH TEMP

    while T > 0.1:
        if cost(board) == 0:
            break

        new_board = board[:]
        col = random.randint(0, 7)
        new_board[col] = random.randint(0, 7)

        delta = cost(board) - cost(new_board)

        if delta > 0 or random.random() < math.exp(delta / T):
            board = new_board

        T = T * 0.98 #DECREASE T

    return board

board = simulated_annealing()

for row in range(8):
    for col in range(8):
        if board[col] == row:
            print("Q", end=" ")
        else:
            print(".", end=" ")
    print()

print("Cost:", cost(board))

if cost(board) == 0:
    print("Solution found!")
else:
    print("Run again.")

